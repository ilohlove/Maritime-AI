"""Single-owner password login and durable opaque sessions; no JWT signing key."""

import hashlib
import hmac
import secrets
import time
from threading import BoundedSemaphore

from sqlalchemy import text
from sqlalchemy.exc import SQLAlchemyError

from app.services.document_ai import WorkflowError
from app.db.session import security_transaction


def digest(value: str) -> str:
    return hashlib.sha256(value.encode()).hexdigest()


def hash_password(password: str) -> str:
    if not 12 <= len(password) <= 256:
        raise ValueError("Use a password of 12–256 characters")
    salt = secrets.token_bytes(16)
    value = hashlib.scrypt(password.encode(), salt=salt, n=16384, r=8, p=5)
    return f"scrypt$16384$8$5${salt.hex()}${value.hex()}"


def validate_password_hash(encoded: str) -> None:
    try:
        algorithm, n, r, p, salt, value = encoded.split("$")
        if (
            (algorithm, n, r, p) != ("scrypt", "16384", "8", "5")
            or len(bytes.fromhex(salt)) != 16
            or len(bytes.fromhex(value)) != 64
        ):
            raise ValueError
    except ValueError:
        raise ValueError(
            "MARITIME_PASSWORD_HASH must be generated by scripts/hash_password.py"
        ) from None


def verify_password(password: str, encoded: str) -> bool:
    salt, expected = encoded.split("$")[-2:]
    actual = hashlib.scrypt(
        password.encode(), salt=bytes.fromhex(salt), n=16384, r=8, p=5
    ).hex()
    return hmac.compare_digest(expected, actual)


def rate_limit(engine, key: str, limit: int, seconds: int = 60) -> None:
    window = int(time.time()) // seconds
    try:
        with security_transaction(engine) as connection:
            connection.execute(
                text(
                    'INSERT INTO rate_windows(key,"window",count) VALUES (:key,:window,1) ON CONFLICT(key) DO UPDATE SET count=CASE WHEN rate_windows."window"=:window THEN rate_windows.count+1 ELSE 1 END,"window"=:window'
                ),
                {"key": key, "window": window},
            )
            count = connection.execute(
                text("SELECT count FROM rate_windows WHERE key=:key"), {"key": key}
            ).scalar_one()
            connection.execute(
                text('DELETE FROM rate_windows WHERE "window" < :old'),
                {"old": window - 2},
            )
            connection.commit()
        if count > limit:
            raise WorkflowError(
                "rate_limited", "Too many attempts. Wait a minute and try again.", 429
            )
    except SQLAlchemyError:
        raise WorkflowError(
            "security_unavailable", "Security storage is unavailable; access denied."
        ) from None


class AuthService:
    def __init__(self, engine, settings):
        self.engine, self.settings = engine, settings
        self.login_slots = BoundedSemaphore(1)

    def login(self, username: str, password: str, client_ip: str):
        # Both counters include successes and failures, and survive restarts.
        rate_limit(self.engine, "login:global", self.settings.login_limit * 6)
        rate_limit(self.engine, "login:" + digest(client_ip), self.settings.login_limit)
        if not self.settings.password_hash:
            raise WorkflowError(
                "auth_not_configured",
                "Configure the backend administrator password hash.",
            )
        if not self.login_slots.acquire(blocking=False):
            raise WorkflowError(
                "login_busy",
                "Another sign-in is being verified. Try again shortly.",
                429,
            )
        try:
            valid = verify_password(password, self.settings.password_hash)
        finally:
            self.login_slots.release()
        if not valid or not hmac.compare_digest(
            username.encode(), self.settings.admin_username.encode()
        ):
            raise WorkflowError(
                "invalid_credentials", "Username or password is incorrect.", 401
            )
        token, csrf = secrets.token_urlsafe(32), secrets.token_urlsafe(32)
        expires = time.time() + self.settings.session_seconds
        try:
            with self.engine.begin() as connection:
                connection.execute(
                    text("DELETE FROM auth_sessions WHERE expires_at<=:now"),
                    {"now": time.time()},
                )
                connection.execute(
                    text(
                        "INSERT INTO auth_sessions(digest,user_id,expires_at,csrf_digest,credential_version) VALUES (:digest,:user,:expires,:csrf,:version)"
                    ),
                    {
                        "digest": digest(token),
                        "user": self.settings.admin_username,
                        "expires": expires,
                        "csrf": digest(csrf),
                        "version": digest(self.settings.password_hash),
                    },
                )
        except SQLAlchemyError:
            raise WorkflowError(
                "security_unavailable", "Cannot create a session; access denied."
            ) from None
        from app.core.disposable import STORAGE_WARNING

        return {
            "storage_warning": STORAGE_WARNING
            if self.settings.disposable_test_mode
            else None,
            "access_token": token,
            "csrf_token": csrf,
            "expires_at": expires,
            "user": self.settings.admin_username,
            "transport": self.settings.auth_transport,
        }

    def authenticate(self, request):
        cookie_mode = self.settings.auth_transport == "cookie"
        authorization = request.headers.get("authorization", "")
        token = (
            request.cookies.get("__Host-maritime_session", "")
            if cookie_mode
            else (authorization[7:] if authorization.startswith("Bearer ") else "")
        )
        if not token or len(token) > 128:
            raise WorkflowError(
                "authentication_required",
                "Sign in to access the private workspace.",
                401,
            )
        try:
            with self.engine.connect() as connection:
                session = (
                    connection.execute(
                        text("SELECT * FROM auth_sessions WHERE digest=:digest"),
                        {"digest": digest(token)},
                    )
                    .mappings()
                    .first()
                )
        except SQLAlchemyError:
            raise WorkflowError(
                "security_unavailable", "Cannot verify the session; access denied."
            ) from None
        if (
            session is None
            or session["expires_at"] <= time.time()
            or not hmac.compare_digest(
                session["credential_version"], digest(self.settings.password_hash)
            )
            or session["user_id"] != self.settings.admin_username
        ):
            raise WorkflowError(
                "session_expired", "Session expired or revoked. Sign in again.", 401
            )
        if (
            cookie_mode
            and request.method not in {"GET", "HEAD", "OPTIONS"}
            and (
                request.headers.get("origin") not in self.settings.allowed_origins
                or not hmac.compare_digest(
                    digest(request.headers.get("x-csrf-token", "")),
                    session["csrf_digest"],
                )
            )
        ):
            raise WorkflowError(
                "csrf_failed", "Refresh your session before making changes.", 403
            )
        request.state.user = session["user_id"]
        request.state.session_digest = session["digest"]

    def logout(self, session_digest: str):
        try:
            with self.engine.begin() as connection:
                connection.execute(
                    text("DELETE FROM auth_sessions WHERE digest=:digest"),
                    {"digest": session_digest},
                )
        except SQLAlchemyError:
            raise WorkflowError(
                "security_unavailable", "Logout could not be confirmed. Retry."
            ) from None
